// Writes docs/TRANSLATIONS.md from src/i18n/en.json and pl.json, so the review
// table always matches what the site shows. Run: npm run translations
import { readFile, writeFile } from 'node:fs/promises';

const en = JSON.parse(await readFile('src/i18n/en.json', 'utf8'));
const pl = JSON.parse(await readFile('src/i18n/pl.json', 'utf8'));

const rows = [];
const walk = (a, b, key) => {
  if (typeof a === 'string') {
    if (a !== b) rows.push([key, a, b]);
    return;
  }
  if (Array.isArray(a)) return a.forEach((v, i) => walk(v, b?.[i], `${key}.${i}`));
  for (const k of Object.keys(a)) walk(a[k], b?.[k], key ? `${key}.${k}` : k);
};
walk(en, pl, '');

const cell = (s) => String(s ?? '(missing)').replace(/\|/g, '\\|');
const table = rows
  .filter(([k]) => !['lang', 'locale', 'otherLang', 'otherLabel', 'otherName'].includes(k))
  .map(([k, a, b]) => `| ${cell(a)} | ${cell(b)} | \`${k}\` |`)
  .join('\n');

await writeFile(
  'docs/TRANSLATIONS.md',
  `# Translations (English and Polish)

Generated by \`npm run translations\` from \`src/i18n/en.json\` and \`src/i18n/pl.json\`. Do not edit this file: change the JSON files, then run the command again. The privacy policy has its own files, \`src/content/privacy/en.md\` and \`pl.md\`.

Rules: the hero tags (FRAMES, CODE), the footer tag (OSKAR), the 404 tag (LOST), product names, timecodes and lines quoted from the films stay in English. No dashes as punctuation in either language. On the site, a one-letter Polish word (a, i, o, u, w, z) is tied to the next word with a no-break space, so it never ends a line; the JSON keeps normal spaces.

Strings that are the same in both languages are left out.

| English | Polski | Key |
| --- | --- | --- |
${table}
`,
);
console.log(`docs/TRANSLATIONS.md: ${rows.length} strings`);
